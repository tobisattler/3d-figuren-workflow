#!/usr/bin/env python3
"""img23d - turnaround images -> textured GLB with ComfyUI + Pixal3D (multi-view).

  img23d.py --views front.png side.png back.png --out figur.glb [--side-faces left] [--res 1024] [--faces 200000] [--tex 2048] [--seed 42]
  img23d.py --front f.png --back b.png --side s.png --other-side o.png --out figur.glb
  img23d.py --image sheet.png --out figur.glb          # sheet with 4 equal panels left-to-right: front, left, back, right
  img23d.py --views ... --out x.glb --dry-run          # only write the API prompt (x.prompt.json), no GPU needed

SIDE VIEWS (found empirically, 06.11.2026): Pixal3D slot "left" wants the figure FACING IMAGE-LEFT, slot "right" the figure
FACING IMAGE-RIGHT. Wrong slots give a second face on the back of the head ("Janus"). If a result shows a doubled face, try
--swap-sides. --side-faces says which way the given side image faces (default: left). A missing opposite side is generated by
mirroring (--no-mirror disables that). --left/--right set the raw Pixal3D slots directly. Always give a back view, too:
without one Pixal3D also tends to invent a face on the back.

Setup: see docs/01-setup.md. The script starts its own ComfyUI on 127.0.0.1:(8190 + GPU index), runs one job, stops it again.
Paths come from the environment (or the matching options):
  COMFY_BASE   folder with ComfyUI/ and venv/  (default: ~/comfy)
  IMG23D_WF    API workflow JSON              (default: comfyui/workflows/pixal3d_mv_api_full.json next to this script)
Measured on an RTX 2080 Ti (11 GB): 117-255 s per run, VRAM peak 8.6-9.8 GB at the defaults below.
"""
import argparse, fcntl, json, os, shutil, signal, subprocess, sys, threading, time, urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
VIEWS = ("front", "left", "back", "right")
SRV = "http://127.0.0.1:8190"


def die(msg, code=2):
    print("img23d: " + msg, file=sys.stderr); sys.exit(code)


def sh(*cmd):
    try:
        return subprocess.run(cmd, capture_output=True, text=True).stdout
    except FileNotFoundError:
        return ""


def gpu_busy(gpu):
    """Refuse a GPU that someone else is using (another model, a render, a game)."""
    q = sh("nvidia-smi", "-i", gpu, "--query-gpu=memory.used,utilization.gpu", "--format=csv,noheader,nounits").strip()
    if not q:
        return []
    mem, util = [int(float(x)) for x in q.split(",")[:2]]
    reasons = []
    if mem > 1500: reasons.append(f"GPU{gpu} memory in use: {mem} MiB")
    if util > 15: reasons.append(f"GPU{gpu} utilisation {util}%")
    return reasons


def api(path, data=None, timeout=30):
    req = urllib.request.Request(SRV + path, data=json.dumps(data).encode() if data is not None else None,
                                 headers={"Content-Type": "application/json"})
    return json.load(urllib.request.urlopen(req, timeout=timeout))


def server_up():
    try:
        api("/system_stats", timeout=3); return True
    except Exception:
        return False


def build_prompt(wf, a):
    """Patch the Comfy template workflow (3d_pixal3d_multi_views, API format): own LoadImage per view, seeds, sizes."""
    p = json.load(open(wf))
    cond = p["324"]["inputs"]                      # Pixal3DMultiViewConditioning: front/left/back/right
    given = {"front": a.front, "left": a.left, "back": a.back, "right": a.right}
    n = 9000
    for view in VIEWS:
        save = cond[view][0]                       # SaveImageAdvanced <- ImageCropToMask <- RemoveBackground/ImageCrop
        mask_crop = p[save]["inputs"]["images"][0]
        imgcrop = p[mask_crop]["inputs"]["images"][0]
        old = [imgcrop, 0]
        if given[view] is None:
            del cond[view]
            continue
        n += 1; lid = str(n)
        p[lid] = {"class_type": "LoadImage", "inputs": {"image": os.path.basename(given[view])}}
        for node in p.values():
            for k, v in node["inputs"].items():
                if v == old:
                    node["inputs"][k] = [lid, 0]
    for seed_node in ("3", "12", "18", "23"):
        p[seed_node]["inputs"]["seed"] = a.seed
    p["94"]["inputs"]["target_resolution"] = a.res     # Trellis2UpsampleStage (template: 1536)
    p["288"]["inputs"]["value"] = a.tex                # texture size (template: 4096)
    p["186"]["inputs"]["target_face_count"] = a.faces  # DecimateMesh (template: 700000)
    p["372"]["inputs"]["filename_prefix"] = a.prefix
    p["372"]["inputs"]["viewport_state"] = ""
    keep, stack = set(), ["372"]                       # keep only the ancestors of the 3D save node
    while stack:
        k = stack.pop()
        if k in keep: continue
        keep.add(k)
        for v in p[k]["inputs"].values():
            if isinstance(v, list) and len(v) == 2 and isinstance(v[0], str) and v[0] in p: stack.append(v[0])
    return {k: v for k, v in p.items() if k in keep}


def split_sheet(path, panels, workdir):
    from PIL import Image
    im = Image.open(path).convert("RGB"); w, h = im.size
    out = {}
    for i, view in enumerate(VIEWS[:panels]):
        f = os.path.join(workdir, f"sheet_{view}.png")
        im.crop((i * w // panels, 0, (i + 1) * w // panels, h)).save(f); out[view] = f
    return out


def main():
    global SRV
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--views", nargs="+", metavar="PNG", help="front [side] [back] [other side] (in this order)")
    ap.add_argument("--front"); ap.add_argument("--back")
    ap.add_argument("--side", help="one side view; see --side-faces")
    ap.add_argument("--side-faces", choices=("left", "right"), default="left", help="direction the figure faces in --side (default: left)")
    ap.add_argument("--other-side", help="the opposite side view (default: --side mirrored)")
    ap.add_argument("--no-mirror", action="store_true")
    ap.add_argument("--swap-sides", action="store_true", help="exchange the left/right slots (other convention)")
    ap.add_argument("--left", help="raw Pixal3D slot 'left'"); ap.add_argument("--right", help="raw Pixal3D slot 'right'")
    ap.add_argument("--image", help="turnaround sheet with 4 equal panels: front, left, back, right")
    ap.add_argument("--out", required=True)
    ap.add_argument("--res", type=int, default=1024, help="Trellis2 upsample resolution (default 1024 fits 11 GB; template uses 1536)")
    ap.add_argument("--faces", type=int, default=200000)
    ap.add_argument("--tex", type=int, default=2048, help="texture size (default 2048; 4096 gives the face more texels, untested on 11 GB)")
    ap.add_argument("--seed", type=int, default=42)
    ap.add_argument("--gpu", default="0", help="GPU index (default 0)")
    ap.add_argument("--comfy-base", default=os.environ.get("COMFY_BASE", os.path.expanduser("~/comfy")))
    ap.add_argument("--workflow", default=os.environ.get("IMG23D_WF", os.path.join(HERE, "comfyui", "workflows", "pixal3d_mv_api_full.json")))
    ap.add_argument("--keep-server", action="store_true", help="leave ComfyUI running after the job")
    ap.add_argument("--force", action="store_true", help="start even if the GPU looks busy")
    ap.add_argument("--dry-run", action="store_true", help="only write OUT.prompt.json (API prompt), do not run")
    a = ap.parse_args()

    base = os.path.abspath(a.comfy_base); comfy = os.path.join(base, "ComfyUI")
    if a.views:
        for name, f in zip(["front", "side", "back", "other_side"], a.views): setattr(a, name, getattr(a, name) or f)
    rundir = os.path.join(base, "run"); os.makedirs(rundir, exist_ok=True)
    work = os.path.join(rundir, f"job-{os.getpid()}"); os.makedirs(work, exist_ok=True)
    if a.image:
        for view, f in split_sheet(a.image, 4, work).items(): setattr(a, view, getattr(a, view) or f)
    if a.side:
        faces = a.side_faces; opp = "right" if faces == "left" else "left"
        if getattr(a, faces) is None: setattr(a, faces, a.side)
        if getattr(a, opp) is None:
            if a.other_side: setattr(a, opp, a.other_side)
            elif not a.no_mirror:
                from PIL import Image, ImageOps
                m = os.path.join(work, f"mirrored_{opp}.png"); ImageOps.mirror(Image.open(a.side).convert("RGB")).save(m); setattr(a, opp, m)
    if a.swap_sides: a.left, a.right = a.right, a.left
    if not a.front: die("front view is required (--views front.png ... or --image sheet.png)")
    for v in VIEWS:
        f = getattr(a, v)
        if f and not os.path.isfile(f): die(f"{v}: file not found: {f}")
    a.prefix = f"3d/img23d_{os.getpid()}"

    if a.dry_run:
        out = os.path.splitext(a.out)[0] + ".prompt.json"
        json.dump(build_prompt(a.workflow, a), open(out, "w"), indent=1)
        print("dry run: wrote", out, "| slots:", {v: getattr(a, v) for v in VIEWS})
        shutil.rmtree(work, ignore_errors=True); return

    if not os.path.isdir(comfy): die(f"ComfyUI not found in {comfy} (set COMFY_BASE or --comfy-base)")
    SRV = f"http://127.0.0.1:{8190 + int(a.gpu)}"
    lk = open(os.path.join(rundir, f"img23d-gpu{a.gpu}.lock"), "w")
    try: fcntl.flock(lk, fcntl.LOCK_EX | fcntl.LOCK_NB)
    except OSError: die(f"another img23d job is running on GPU{a.gpu}", 4)
    if not server_up() and not a.force:
        busy = gpu_busy(a.gpu)
        if busy: die("GPU looks busy: " + "; ".join(busy) + " (use --force to start anyway)", 4)
    print(f"using GPU {a.gpu}", flush=True)

    proc = None
    if not server_up():
        py = os.path.join(base, "venv", "bin", "python")
        if not os.path.exists(py): py = sys.executable
        log = open(os.path.join(rundir, f"server-gpu{a.gpu}.log"), "ab")
        env = dict(os.environ, CUDA_VISIBLE_DEVICES=a.gpu, PYTHONUNBUFFERED="1", DO_NOT_TRACK="1")
        proc = subprocess.Popen([py, "main.py", "--listen", "127.0.0.1", "--port", SRV.rsplit(":", 1)[1], "--disable-auto-launch",
                                 "--dont-print-server", "--disable-api-nodes"], cwd=comfy, stdout=log, stderr=log,
                                stdin=subprocess.DEVNULL, start_new_session=True, env=env)
        for _ in range(180):
            if server_up(): break
            if proc.poll() is not None: die(f"ComfyUI exited (see {rundir}/server-gpu{a.gpu}.log)", 5)
            time.sleep(1)
        else: die(f"ComfyUI did not come up (see {rundir}/server-gpu{a.gpu}.log)", 5)

    peak = [0]; stop = threading.Event()
    def sampler():
        while not stop.is_set():
            q = sh("nvidia-smi", "-i", a.gpu, "--query-gpu=memory.used", "--format=csv,noheader,nounits").strip()
            if q: peak[0] = max(peak[0], int(float(q)))
            stop.wait(1)
    threading.Thread(target=sampler, daemon=True).start()
    t0 = time.time(); copied = []
    try:
        for v in VIEWS:
            f = getattr(a, v)
            if f:
                dst = os.path.join(comfy, "input", f"img23d_{os.getpid()}_{v}.png")
                shutil.copy(f, dst); setattr(a, v, dst); copied.append(dst)
        prompt = build_prompt(a.workflow, a)
        outdir = os.path.join(comfy, "output", os.path.dirname(a.prefix)); stem = os.path.basename(a.prefix)
        r = api("/prompt", {"prompt": prompt})
        if r.get("node_errors"): die("workflow rejected: " + json.dumps(r["node_errors"])[:1500], 6)
        pid = r["prompt_id"]; print(f"queued {pid}; views: " + ", ".join(v for v in VIEWS if getattr(a, v)), flush=True)
        while True:
            h = api(f"/history/{pid}").get(pid)
            if h and h.get("status", {}).get("status_str") in ("success", "error"): break
            time.sleep(3)
        st = h["status"]
        if st.get("status_str") != "success":
            msgs = [m for m in st.get("messages", []) if m[0] == "execution_error"]
            die("job failed: " + json.dumps(msgs[-1][1] if msgs else st)[:2500], 7)
        new = sorted(f for f in os.listdir(outdir) if f.startswith(stem) and f.lower().endswith((".glb", ".gltf")))
        if not new: die("job finished but no GLB found in " + outdir, 8)
        os.makedirs(os.path.dirname(os.path.abspath(a.out)) or ".", exist_ok=True)
        shutil.copy(os.path.join(outdir, new[-1]), a.out)
        print(f"OK {a.out} ({os.path.getsize(a.out)/1e6:.1f} MB) in {time.time()-t0:.0f}s, GPU{a.gpu} VRAM peak {peak[0]} MiB")
    finally:
        stop.set()
        for f in copied:
            try: os.remove(f)
            except OSError: pass
        shutil.rmtree(work, ignore_errors=True)
        if proc is not None and not a.keep_server:
            try: os.killpg(proc.pid, signal.SIGTERM); proc.wait(timeout=30)
            except Exception: pass


if __name__ == "__main__":
    main()
